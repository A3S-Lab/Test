export type ReviewI18n = {
  locale: ResolvedReviewLocale;
  t: ReviewTranslator;
};

const DEFAULT_I18N = createReviewI18n("en");
const ReviewI18nContext = createContext<ReviewI18n>(DEFAULT_I18N);

export function ReviewI18nProvider({ children, value }: { children: ReactNode; value: ReviewI18n }) {
  return <ReviewI18nContext.Provider value={value}>{children}</ReviewI18nContext.Provider>;
}

export function useReviewI18n(): ReviewI18n {
  return useContext(ReviewI18nContext);
}

export function useReviewI18nConfig(
  locale: A3SReviewLocale = "auto",
  overrides?: A3SReviewMessageOverrides,
): ReviewI18n {
  const [pageLanguage, setPageLanguage] = useState(readPageLanguage);
  const admittedOverrides = overrides ?? EMPTY_REVIEW_MESSAGE_OVERRIDES;

  useEffect(() => {
    if (locale !== "auto" || typeof document === "undefined") return;
    const root = document.documentElement;
    const update = () => {
      const next = root.lang;
      setPageLanguage((current) => current === next ? current : next);
    };
    update();
    if (typeof MutationObserver === "undefined") return;
    const observer = new MutationObserver(update);
    observer.observe(root, { attributes: true, attributeFilter: ["lang"] });
    return () => observer.disconnect();
  }, [locale]);

  return useMemo(
    () => createReviewI18n(locale, admittedOverrides, pageLanguage),
    [locale, admittedOverrides, pageLanguage],
  );
}

export function resolveReviewLocale(locale: A3SReviewLocale = "auto", pageLanguage = ""): ResolvedReviewLocale {
  const candidate = locale === "auto" ? pageLanguage : locale;
  return candidate.trim().toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

function readPageLanguage(): string {
  return typeof document === "undefined" ? "" : document.documentElement.lang;
}

export function createReviewI18n(
  locale: A3SReviewLocale = "auto",
  overrides: A3SReviewMessageOverrides = {},
  pageLanguage = "",
): ReviewI18n {
  const resolved = resolveReviewLocale(locale, pageLanguage);
  const localized = resolved === "zh-CN" ? ZH_CN_REVIEW_MESSAGES : EN_REVIEW_MESSAGES;
  const catalog = { ...localized } as Record<A3SReviewMessageKey, string>;
  for (const key of Object.keys(EN_REVIEW_MESSAGES) as A3SReviewMessageKey[]) {
    const override = overrides[key];
    if (typeof override === "string" && override.trim() && override.length <= 2_048) {
      catalog[key] = override;
    }
  }
  return {
    locale: resolved,
    t: (key, values = {}) => catalog[key].replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name: string) => (
      Object.hasOwn(values, name) ? String(values[name]) : placeholder
    )),
  };
}

