export function reviewTargetSummary(t: ReviewTranslator, target: RepairTarget): string {
  if (target.layout?.kind === "placement") {
    const canvas = target.layout.canvas === "wireframe" ? t("wireframe") : t("currentPage");
    return t("layoutPlacementSummary", { component: target.layout.componentType, canvas });
  }
  if (target.layout?.kind === "rearrange") return t(target.nodeIds.length === 1 ? "layoutRearrangementSummaryOne" : "layoutRearrangementSummaryMany", { count: target.nodeIds.length });
  if (target.kind === "text") return t("textSummary", { selection: target.selectedText?.slice(0, 36) ?? t("selection") });
  if (target.kind === "region") return t("areaSummary", { count: target.nodeIds.length });
  if (target.kind === "drawing") return t("drawingSummary", { count: target.nodeIds.length });
  return t(target.nodeIds.length === 1 ? "elementSummaryOne" : "elementSummaryMany", { count: target.nodeIds.length });
}

export function reviewRepairAnnouncement(t: ReviewTranslator, repair: SubmittedRepair): string {
  if (repair.status === "needs_input") return t("repairNeedsInput", { message: repair.instruction });
  if (repair.status === "review_ready") return t("repairReadyReview", { message: repair.instruction });
  return t("repairStatusAnnouncement", { status: reviewStatusLabel(t, repair.status), message: repair.instruction });
}

export function reviewActorLabel(t: ReviewTranslator, actor: "human" | "agent" | "a3s-test"): string {
  if (actor === "human") return t("actorHuman");
  if (actor === "agent") return t("actorAgent");
  return t("actorA3STest");
}

